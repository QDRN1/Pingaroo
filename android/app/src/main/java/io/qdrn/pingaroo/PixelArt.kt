    fun textWidth(text: String, scale: Float): Float = text.length * 6f * scale

    fun drawText(c: Canvas, text: String, x: Float, y: Float, scale: Float, color: Int, paint: Paint) {
        paint.color = color
        var cx = x
        for (ch in text.uppercase()) {
            val g = GLYPHS[ch] ?: GLYPHS[' ']!!
            for ((gy, row) in g.withIndex()) for ((gx, cell) in row.withIndex()) {
                if (cell == '#') c.drawRect(cx + gx * scale, y + gy * scale, cx + (gx + 1) * scale, y + (gy + 1) * scale, paint)
            }
            cx += 6f * scale
        }
    }

    fun drawKangaroo(c: Canvas, x: Float, y: Float, scale: Float, paint: Paint) {
        for ((ry, row) in KANGAROO.withIndex()) for ((rx, cell) in row.withIndex()) {
            if (cell == '.') continue
            paint.color = when (cell) {
                'o' -> EYE
                'p' -> POUCH
                'w' -> WIFI
                else -> if (ry > 18 || rx < 8) FUR_DARK else FUR
            }
            c.drawRect(x + rx * scale, y + ry * scale, x + (rx + 1) * scale, y + (ry + 1) * scale, paint)
        }
    }

    val KANGAROO_W = KANGAROO[0].length
    val KANGAROO_H = KANGAROO.size
